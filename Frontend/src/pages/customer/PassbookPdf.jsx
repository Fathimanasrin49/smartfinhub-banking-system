function formatDate(d) {
  return new Date(d).toLocaleDateString('en-IN');
}

function formatAmount(n) {
  return new Intl.NumberFormat('en-IN', { style: 'currency', currency: 'INR' }).format(n);
}

export function PassbookDocument({ profile = {}, transactions = [], startDate = '', endDate = '' }) {
  const name = profile.name || 'Customer';
  const accountNumber = profile.account_number || '—';
  const period =
    startDate && endDate
      ? `${formatDate(startDate)} to ${formatDate(endDate)}`
      : startDate
        ? `From ${formatDate(startDate)}`
        : endDate
          ? `Until ${formatDate(endDate)}`
          : 'All time';

  return (
    <Document>
      <Page size="A4" style={styles.page}>
        <Text style={styles.title}>Passbook</Text>
        <Text style={styles.subtitle}>Smart FinHub — Transaction history</Text>

        <View style={styles.meta}>
          <View style={styles.metaBlock}>
            <Text style={styles.metaLabel}>Account holder</Text>
            <Text style={styles.metaValue}>{name}</Text>
          </View>
          <View style={styles.metaBlock}>
            <Text style={styles.metaLabel}>Account number</Text>
            <Text style={styles.metaValue}>{accountNumber}</Text>
          </View>
          <View style={styles.metaBlock}>
            <Text style={styles.metaLabel}>Period</Text>
            <Text style={styles.metaValue}>{period}</Text>
          </View>
          <View style={styles.metaBlock}>
            <Text style={styles.metaLabel}>Generated</Text>
            <Text style={styles.metaValue}>{formatDate(new Date())}</Text>
          </View>
        </View>

        <View style={styles.table}>
          <View style={styles.tableHeader}>
            <Text style={[styles.headerText, styles.colDate]}>Date</Text>
            <Text style={[styles.headerText, styles.colType]}>Type</Text>
            <Text style={[styles.headerText, styles.colDesc]}>Description</Text>
            <Text style={[styles.headerText, styles.colCategory]}>Category</Text>
            <Text style={[styles.headerText, styles.colAmount]}>Amount</Text>
          </View>
          {transactions.map((t) => (
            <View key={t.id} style={styles.tableRow}>
              <Text style={[styles.cellText, styles.colDate]}>{formatDate(t.created_at)}</Text>
              <Text style={[styles.cellText, styles.colType]}>{t.type}</Text>
              <Text style={[styles.cellText, styles.colDesc]}>{t.description || t.transaction_id || '—'}</Text>
              <Text style={[styles.cellText, styles.colCategory]}>{t.category || '—'}</Text>
              <Text
                style={[
                  t.type === 'credit' ? styles.amountCredit : styles.amountDebit,
                  styles.colAmount,
                ]}
              >
                {t.type === 'credit' ? '+' : '-'}{formatAmount(t.amount)}
              </Text>
            </View>
          ))}
        </View>

        <Text style={styles.footer}>
          This passbook is generated by Smart FinHub. It contains {transactions.length} transaction(s) for the selected period.
        </Text>
      </Page>
    </Document>
  );
}
